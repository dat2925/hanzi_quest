test("1C teaches four tones before nine checks, six recall cards and only two learned words", () => {
  assert.equal(book1c.status, "draft");
  assert.equal(book1c.lessons.length, 1);
  assert.deepEqual(lesson1c.prerequisites, [lesson1b.id]);
  assert.deepEqual(book1c.references, [
    { ...book1.lessons[0], status: "published" },
    { ...book1b.lessons[0], status: "published" },
  ]);
  assert.deepEqual(
    lesson1c.learning!.screens.map((s) => s.kind),
    [
      "objective",
      "pronunciation",
      "vocabulary",
      "recall",
      "notebook",
      "assessment",
      "srs",
    ],
  );
  assert.deepEqual(
    lesson1c.learning!.screens.flatMap((s) =>
      s.kind === "vocabulary"
        ? s.words.map((w) => [w.hanzi, w.pinyin, w.tones])
        : [],
    ),
    [
      ["妈", "mā", [1]],
      ["爸", "bà", [4]],
    ],
  );
  const tones = lesson1c.learning!.screens[1];
  assert.ok(tones.kind === "pronunciation");
  assert.equal(tones.speech, undefined);
  assert.equal(tones.listenToExamples, true);
  assert.deepEqual(
    tones.examples.map((e) => e.pinyin),
    ["mā", "má", "mǎ", "mà"],
  );
  assert.match(tones.body, /khi nói liền thường chỉ thấp/);
  assert.equal(lesson1c.questions.length, 9);
  assert.equal(new Set(lesson1c.questions.map(questionKey)).size, 9);
  assert.ok(lesson1c.questions.every((q) => !JSON.stringify(q).match(/麻|骂/)));
  const recall = lesson1c.learning!.screens.find((s) => s.kind === "recall")!;
  assert.equal(recall.cards.length, 6);
  for (const hanzi of ["妈", "爸"])
    assert.deepEqual(
      recall.cards
        .filter((c) => c.hanzi === hanzi)
        .map((c) => c.answerType)
        .sort(),
      ["hanzi", "meaning", "pinyin"],
    );
  assert.equal(
    canStudy(initial, lesson1c, [lesson1a, lesson1b, lesson1c]),
    false,
  );
  assert.equal(
    canStudy({ ...initial, completed: [lesson1a.id] }, lesson1c, [
      lesson1a,
      lesson1b,
      lesson1c,
    ]),
    false,
  );
  assert.equal(
    canStudy({ ...initial, completed: [lesson1a.id, lesson1b.id] }, lesson1c, [
      lesson1a,
      lesson1b,
      lesson1c,
    ]),
    true,
  );
  const bad = structuredClone(book1c);
  bad.lessons[0].screens.find(
    (s) => s.kind === "assessment",
  )!.items[0].question.prompt = "麻 có nghĩa là gì?";
  assert.throws(() => validateBundle(bad), /chữ chưa giới thiệu/);
  const untaught = structuredClone(book1c);
  untaught.lessons[0].screens.find(
    (s) => s.kind === "assessment",
  )!.items[0].question.knowledge = ["untaught"];
  assert.throws(() => validateBundle(untaught), /kiến thức chưa dạy/);
});

test("1C additive SQL preserves 1A/1B, ten samples and five accounts; validates both refs, RLS, promotion, XP and SRS", async () => {
  const db = new PGlite();
  const dir = mkdtempSync(join(tmpdir(), "hanzione-1c-"));
  const ids = Array.from(
    { length: 5 },
    (_, i) => `60000000-0000-4000-8000-00000000000${i + 1}`,
  );
  const draft = readFileSync(
    "supabase/migrations/202610130003_book1_lesson1c_draft.sql",
    "utf8",
  );
  const publish = readFileSync(
    "supabase/manual/book1_lesson1c_publish_after_review.sql",
    "utf8",
  );
  const as = (id: string) =>
    db.exec(
      `reset role;set role authenticated;select set_config('request.jwt.claim.sub','${id}',false);`,
    );
  const snapshot = async () =>
    (
      await db.query<{ value: any }>(
        "select public.learning_snapshot() as value",
      )
    ).rows[0].value;
  const apply = (op: unknown) =>
    db.query("select public.apply_learning_operation($1::jsonb)", [
      JSON.stringify(op),
    ]);
  const finish = (lesson: Lesson, wrongIndex = -1) =>
    operation("finish", {
      lessonId: lesson.id,
      seconds: 120,
      endedAt: Date.now(),
      questions: lesson.questions.map((q, i) => ({
        key: questionKey(q),
        selection:
          i === wrongIndex ? q.options.find((o) => o !== q.answer)! : q.answer,
        assisted: false,
      })),
    });
  try {
    // Reproducible SQL generated by the existing importer, never by a production client.
    for (const mode of ["--draft-sql", "--promote-sql"]) {
      const source = structuredClone(book1c);
      if (mode === "--promote-sql") {
        source.status = "published";
        source.lessons[0].status = "published";
      }
      const input = join(dir, "input.json"),
        output = join(dir, mode + ".sql");
      writeFileSync(input, JSON.stringify(source));
      execFileSync(process.execPath, [
        "--import",
        "tsx",
        "scripts/import-curriculum.ts",
        input,
        mode,
        output,
      ]);
      assert.equal(
        readFileSync(output, "utf8"),
        mode === "--draft-sql" ? draft : publish,
      );
    }
    await db.exec(
      "create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key,raw_user_meta_data jsonb default '{}');create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema auth to authenticated,anon;grant execute on function auth.uid() to authenticated,anon;",
    );
    for (const id of ids)
      await db.query("insert into auth.users(id) values($1)", [id]);
    for (const name of [
      "202610120001_schema.sql",
      "202610120002_sample_content.sql",
      "202610120003_legacy_approval.sql",
      "202610120004_learning_structure.sql",
      "202610130001_book1_lesson1a_draft.sql",
    ])
      await db.exec(readFileSync(`supabase/migrations/${name}`, "utf8"));
    await db.exec(
      readFileSync(
        "supabase/manual/book1_lesson1a_publish_after_review.sql",
        "utf8",
      ),
    );
    await db.exec(
      readFileSync(
        "supabase/migrations/202610130002_book1_lesson1b_draft.sql",
        "utf8",
      ),
    );
    await db.exec(
      readFileSync(
        "supabase/manual/book1_lesson1b_publish_after_review.sql",
        "utf8",
      ),
    );
    for (const id of ids) {
      await as(id);
      await apply(finish(lessons[0]));
    }
    await as(ids[0]);
    await apply(finish(lesson1a));
    await apply(finish(lesson1b));
    await as(ids[1]);
    await apply(finish(lesson1a));
    const before = [];
    for (const id of ids) {
      await as(id);
      before.push(await snapshot());
    }
    await db.exec("reset role;");
    const oldLessons = (
      await db.query<{ id: string; content_json: unknown }>(
        "select * from public.lessons order by id",
      )
    ).rows;
    const oldUnits = (await db.query("select * from public.units order by id"))
      .rows;
    const oldVocab = (
      await db.query("select * from public.vocabulary order by id")
    ).rows;
    assert.equal(oldLessons.length, 12);
    for (const ref of [lesson1a, lesson1b]) {
      await db.query(
        "update public.lessons set is_published=false where id=$1",
        [ref.id],
      );
      for (const sql of [draft, publish]) {
        await assert.rejects(() => db.exec(sql), /REFERENCE_MISMATCH/);
        await db.exec("rollback;");
      }
      await db.query(
        "update public.lessons set is_published=true where id=$1",
        [ref.id],
      );
      const content = JSON.stringify(
        oldLessons.find((l: any) => l.id === ref.id)!.content_json,
      );
      await db.query(
        "update public.lessons set content_json=jsonb_set(content_json,'{learning,description}','\"changed\"') where id=$1",
        [ref.id],
      );
      await assert.rejects(() => db.exec(draft), /REFERENCE_MISMATCH/);
      await db.exec("rollback;");
      await db.query(
        "update public.lessons set content_json=$1::jsonb where id=$2",
        [content, ref.id],
      );
    }
    await db.exec(draft);
    for (const [i, id] of ids.entries()) {
      await as(id);
      assert.deepEqual(await snapshot(), before[i]);
      assert.equal(
        (
          await db.query(
            "select id from public.lessons where id='hanzione-b1-l01c'",
          )
        ).rows.length,
        0,
      );
    }
    await assert.rejects(() => apply(finish(lesson1c)), /UNKNOWN_LESSON/);
    await db.exec("reset role;");
    assert.deepEqual(
      (
        await db.query(
          "select * from public.lessons where id<>'hanzione-b1-l01c' order by id",
        )
      ).rows,
      oldLessons,
    );
    assert.deepEqual(
      (await db.query("select * from public.units order by id")).rows,
      oldUnits,
    );
    assert.deepEqual(
      (
        await db.query(
          "select * from public.vocabulary where id=any($1::text[]) order by id",
          [oldVocab.map((w: any) => w.id)],
        )
      ).rows,
      oldVocab,
    );
    await db.exec(
      "update public.lessons set content_json=jsonb_set(content_json,'{minutes}','99') where id='hanzione-b1-l01c';",
    );
    await assert.rejects(() => db.exec(publish), /DRAFT_CONTENT_MISMATCH/);
    await db.exec(
      "rollback;update public.lessons set content_json=jsonb_set(content_json,'{minutes}','16') where id='hanzione-b1-l01c';",
    );
    await db.exec(publish);
    await as(ids[1]);
    await assert.rejects(() => apply(finish(lesson1c)), /LESSON_LOCKED/);
    await as(ids[0]);
    const op = finish(lesson1c, 3); // One wrong tone question: eight correct out of nine.
    await apply(op);
    await apply(op);
    const learned = await snapshot();
    assert.equal(learned.progress.xp, before[0].progress.xp + 38);
    assert.ok(learned.progress.completed.includes(lesson1c.id));
    for (const hanzi of ["妈", "爸"]) {
      assert.equal(learned.progress.reviews[hanzi].interval, 1);
      assert.ok(learned.progress.reviews[hanzi].due > Date.now());
    }
    for (const [hanzi, review] of Object.entries(before[0].progress.reviews))
      assert.deepEqual(learned.progress.reviews[hanzi], review);
    assert.ok(
      !learned.progress.reviews["麻"] && !learned.progress.reviews["骂"],
    );
    const review = operation("review", { hanzi: "妈", correct: false });
    await apply(review);
    await apply(review);
    const forgotten = await snapshot();
    assert.equal(forgotten.progress.xp, learned.progress.xp);
    assert.equal(forgotten.progress.reviews["妈"].interval, 0);
    assert.equal(
      forgotten.progress.reviews["妈"].attempts,
      learned.progress.reviews["妈"].attempts + 1,
    );
    assert.ok(forgotten.progress.reviews["妈"].due - Date.now() <= 610000);
    for (const [i, id] of ids.entries())
      if (i !== 0) {
        await as(id);
        assert.deepEqual(await snapshot(), before[i]);
      }
    await db.exec("reset role;");
    assert.deepEqual(
      (
        await db.query(
          "select * from public.lessons where id<>'hanzione-b1-l01c' order by id",
        )
      ).rows,
      oldLessons,
    );
    assert.deepEqual(
      (
        await db.query(
          "select * from public.vocabulary where id=any($1::text[]) order by id",
          [oldVocab.map((w: any) => w.id)],
        )
      ).rows,
      oldVocab,
    );
    await assert.rejects(
      () => db.exec(draft),
      /LESSON_ID_EXISTS_USE_NEW_REVISION/,
    );
    await db.exec("rollback;");
  } finally {
    await db.close();
    rmSync(dir, { recursive: true, force: true });
  }
});
